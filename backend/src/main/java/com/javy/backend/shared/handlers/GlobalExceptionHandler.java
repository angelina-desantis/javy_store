package com.javy.backend.shared.handlers;

import com.javy.backend.shared.dto.ApiResult;
import com.javy.backend.shared.exceptions.*;
import com.javy.backend.shared.logging.CorrelationIdFilter;
import jakarta.validation.ConstraintViolationException;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.slf4j.MDC;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.http.converter.HttpMessageNotReadableException;
import org.springframework.validation.BindException;
import org.springframework.web.bind.MethodArgumentNotValidException;
import org.springframework.web.bind.annotation.ExceptionHandler;
import org.springframework.web.bind.annotation.RestControllerAdvice;
import org.springframework.web.method.annotation.MethodArgumentTypeMismatchException;
import tools.jackson.databind.exc.InvalidFormatException;

import java.time.Instant;
import java.util.HashMap;
import java.util.Map;

/**
 * Global exception handler.
 *
 * <p>
 * This class intercepts exceptions thrown by controllers and services
 * and converts them into standardized API responses using {@link ApiResult}.
 * </p>
 * <p>
 * Each handler logs the exception along with a correlation ID to improve traceability.
 * </p>
 */
@RestControllerAdvice
public class GlobalExceptionHandler {

    private static final Logger log = LoggerFactory.getLogger(GlobalExceptionHandler.class);

    /**
     * Retrieves the correlation ID for the current request.
     *
     * <p>
     * The correlation ID is generated by {@link CorrelationIdFilter}
     * and stored in the Mapped Diagnostic Context (MDC).
     * </p>
     *
     * @return the correlation ID or {@code null} if not present
     */
    private String cid() {
        return MDC.get("correlationId");
    }

    /**
     * Handles binding and validation failures for non-JSON inputs such as
     * form data, query parameters, and other request types where Spring
     * performs data binding before validation.
     */
    @ExceptionHandler(BindException.class)
    public ResponseEntity<ApiResult<Map<String, String>>> handleBindException(BindException ex) {

        log.warn("BindException [{}]: validation failed. Errors={}", cid(), ex.getBindingResult().getFieldErrors());

        Map<String, String> errors = new HashMap<>();
        ex.getBindingResult().getFieldErrors()
                .forEach(error -> errors.put(error.getField(), error.getDefaultMessage()));

        return ResponseEntity.badRequest().body(
                new ApiResult<>(false, "Validation failed.", errors, Instant.now())
        );
    }

    /**
     * Handles validation failures for method parameters such as path variables,
     * query parameters, and other non-body inputs.
     */
    @ExceptionHandler(ConstraintViolationException.class)
    public ResponseEntity<ApiResult<Map<String, String>>> handleConstraintViolation(ConstraintViolationException ex) {

        log.warn("ConstraintViolation [{}]: {}", cid(), ex.getMessage());

        Map<String, String> errors = new HashMap<>();
        ex.getConstraintViolations().forEach(v ->
                errors.put(v.getPropertyPath().toString(), v.getMessage())
        );

        return ResponseEntity.badRequest().body(
                new ApiResult<>(false, "Validation failed.", errors, Instant.now())
        );
    }

    /**
     * Handles invalid enum values passed to controller parameters.
     */
    @ExceptionHandler(MethodArgumentTypeMismatchException.class)
    public ResponseEntity<ApiResult<Void>> handleEnumConversion(MethodArgumentTypeMismatchException ex) {

        log.warn("TypeMismatch [{}]: parameter={} value={}", cid(), ex.getName(), ex.getValue());

        String message = "Invalid value for parameter '" + ex.getName() + "'.";

        return ResponseEntity.badRequest().body(
                new ApiResult<>(false, message, null, Instant.now())
        );
    }

    /**
     * Handles requests for resources that do not exist.
     */
    @ExceptionHandler(NotFoundException.class)
    public ResponseEntity<ApiResult<Void>> handleNotFound(NotFoundException ex) {

        log.info("NotFound [{}]: {}", cid(), ex.getMessage());

        return ResponseEntity.status(HttpStatus.NOT_FOUND).body(
                new ApiResult<>(false, ex.getMessage(), null, Instant.now())
        );
    }

    /**
     * Handles invalid business operations.
     */
    @ExceptionHandler(BadRequestException.class)
    public ResponseEntity<ApiResult<Void>> handleBadRequest(BadRequestException ex) {

        log.warn("BadRequest [{}]: {}", cid(), ex.getMessage());

        return ResponseEntity.badRequest().body(
                new ApiResult<>(false, ex.getMessage(), null, Instant.now())
        );
    }

    /**
     * Handles authentication failures.
     */
    @ExceptionHandler(UnauthorizedException.class)
    public ResponseEntity<ApiResult<Void>> handleUnauthorized(UnauthorizedException ex) {

        log.info("Unauthorized [{}]: {}", cid(), ex.getMessage());

        return ResponseEntity.status(HttpStatus.UNAUTHORIZED).body(
                new ApiResult<>(false, ex.getMessage(), null, Instant.now())
        );
    }

    /**
     * Handles authorization failures where the user is authenticated
     * but does not have permission to perform an operation.
     */
    @ExceptionHandler(ForbiddenException.class)
    public ResponseEntity<ApiResult<Void>> handleForbidden(ForbiddenException ex) {

        log.info("Forbidden [{}]: {}", cid(), ex.getMessage());

        return ResponseEntity.status(HttpStatus.FORBIDDEN).body(
                new ApiResult<>(false, ex.getMessage(), null, Instant.now())
        );
    }

    /**
     * Handles conflicts with existing application state.
     */
    @ExceptionHandler(ConflictException.class)
    public ResponseEntity<ApiResult<Void>> handleConflict(ConflictException ex) {

        log.warn("Conflict [{}]: {}", cid(), ex.getMessage());

        return ResponseEntity.status(HttpStatus.CONFLICT).body(
                new ApiResult<>(false, ex.getMessage(), null, Instant.now())
        );
    }

    /**
     * Handles failures caused by external service calls.
     *
     * <p>
     * These errors typically originate from third-party APIs such as Supabase,
     * Stripe, or other external dependencies.
     * </p>
     */
    @ExceptionHandler(ExternalServiceException.class)
    public ResponseEntity<ApiResult<Void>> handleExternalService(ExternalServiceException ex) {

        log.error("ExternalService [{}]: {}", cid(), ex.getMessage());

        return ResponseEntity.status(HttpStatus.BAD_GATEWAY).body(
                new ApiResult<>(false, ex.getMessage(), null, Instant.now())
        );
    }

    /**
     * Handles bean validation failures from request DTOs.
     */
    @ExceptionHandler(MethodArgumentNotValidException.class)
    public ResponseEntity<ApiResult<Map<String, String>>> handleValidation(MethodArgumentNotValidException ex) {

        log.warn("Validation [{}]: {}", cid(), ex.getMessage());

        Map<String, String> errors = new HashMap<>();
        ex.getBindingResult().getFieldErrors()
                .forEach(error -> errors.put(error.getField(), error.getDefaultMessage()));

        return ResponseEntity.badRequest().body(
                new ApiResult<>(false, "Validation failed.", errors, Instant.now())
        );
    }

    /**
     * Handles malformed JSON request bodies.
     */
    @ExceptionHandler(HttpMessageNotReadableException.class)
    public ResponseEntity<ApiResult<Void>> handleMalformedJson(HttpMessageNotReadableException ex) {

        log.warn("MalformedJSON [{}]: {}", cid(), ex.getMessage());

        Throwable cause = ex.getCause();

        if (cause instanceof InvalidFormatException invalid) {

            String message = invalid.getMessage();
            String field = "unknown";

            int start = message.lastIndexOf("[\"") + 2;
            int end = message.lastIndexOf("\"]");

            if (start > 1 && end > start) {
                field = message.substring(start, end);
            }

            return ResponseEntity.badRequest().body(
                    new ApiResult<>(false, "Invalid value for field '" + field + "'.", null, Instant.now())
            );
        }

        return ResponseEntity.badRequest().body(
                new ApiResult<>(false, "Malformed JSON request.", null, Instant.now())
        );
    }

    /**
     * Handles unexpected application errors.
     *
     * <p>
     * These errors represent failures that were not anticipated by the
     * application logic and typically indicate bugs or unhandled states.
     * </p>
     */
    @ExceptionHandler(Exception.class)
    public ResponseEntity<ApiResult<Void>> handleUnexpected(Exception ex) {

        log.error("Unexpected [{}]: {}", cid(), ex.getMessage(), ex);

        return ResponseEntity.status(HttpStatus.INTERNAL_SERVER_ERROR).body(
                new ApiResult<>(false, "An unexpected error occurred.", null, Instant.now())
        );
    }
}